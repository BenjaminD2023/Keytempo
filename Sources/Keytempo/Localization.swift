import Foundation

/// UI language is independent of the keyboard/input-method languages being monitored.
/// Internal classifications and status values keep stable identifiers; translate at display time.
enum AppLanguage {
    static var code: String { UserDefaults.standard.string(forKey: "interfaceLanguage") == "en" ? "en" : "zh-Hans" }
    static var currentLocale: Locale { Locale(identifier: code) }

    static func translated(_ key: String, language: String, arguments: [CVarArg] = []) -> String {
        let format = language == "en" ? englishText(key) : key
        return arguments.isEmpty ? format : String(format: format, locale: Locale(identifier: language), arguments: arguments)
    }

    private static func englishText(_ key: String) -> String {
        if let value = english[key] { return value }
        // These prefixes are emitted by this app. Preserve external error descriptions verbatim.
        for (prefix, translation) in errorPrefixes where key.hasPrefix(prefix) {
            return translation + String(key.dropFirst(prefix.count))
        }
        if key.hasPrefix("中断 · ") { return "Interrupted · " + englishText(String(key.dropFirst("中断 · ".count))) }
        if key.hasPrefix("事件缓冲区溢出；已丢弃 "), key.hasSuffix(" 个事件") {
            let value = key.dropFirst("事件缓冲区溢出；已丢弃 ".count).dropLast(" 个事件".count)
            if UInt64(value) != nil { return "Event buffer overflow; dropped \(value) events" }
        }
        for prefix in ["输入法：组合用途需适配器确认", "键盘布局"] where key.hasPrefix(prefix + " · ") {
            let code = String(key.dropFirst((prefix + " · ").count))
            if code.range(of: "^[a-z]{2,3}$", options: .regularExpression) != nil {
                return (english[prefix] ?? prefix) + " · " + code
            }
        }
        // Unknown/external strings are never changed by substring replacement.
        return key
    }

