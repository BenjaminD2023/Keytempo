/// Pure checks; no preference changes or UI automation.
func runLocalizationChecks() -> [String] {
    var failures: [String] = []
    func expect(_ value: Bool, _ label: String) { if !value { failures.append("FAIL: localization \(label)") } }
    expect(AppLanguage.translated("暂停统计", language: "en") == "Pause", "English label")
    expect(AppLanguage.translated("暂停统计", language: "zh-Hans") == "暂停统计", "Chinese label")
    expect(AppLanguage.translated("当前：%@", language: "en", arguments: ["中文应用"]) == "Current: 中文应用", "external app name preserved")
    expect(AppLanguage.translated("%d 分 %d 秒", language: "en", arguments: [1, 12]) == "1 min 12 s", "duration placeholders")
    expect(AppLanguage.translated("正在统计 · 已确认输入段", language: "en") == "Counting · Confirmed burst", "confirmed status")
    expect(AppLanguage.translated("保存失败：外部错误", language: "en") == "Save failed: 外部错误", "external error preserved")
    expect(AppLanguage.translated("中断 · 输入源语言已排除", language: "en") == "Interrupted · Input-source language excluded", "interruption reason")
    expect(AppLanguage.translated("事件缓冲区溢出；已丢弃 42 个事件", language: "en") == "Event buffer overflow; dropped 42 events", "bounded overflow count")
    expect(AppLanguage.translated("键盘布局 · en", language: "en") == "Keyboard layout · en", "input-source code preserved")
    expect(AppLanguage.translated("当前输入段", language: "en") == "Current typing burst", "current burst label")
    expect(AppLanguage.translated("最近完成：%@ · %@ · %@", language: "en", arguments: ["English", "Global estimate", "12:00"]) == "Last completed: English · Global estimate · 12:00", "completed segment metadata")
    expect(AppLanguage.translated("私人应用 暂停统计", language: "en") == "私人应用 暂停统计", "unknown strings untouched")
